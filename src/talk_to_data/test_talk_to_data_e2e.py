class MockLLMClient(LLMClient):
    """Mock LLM Client for simulating various LLM response conditions."""

    def __init__(self, mock_response: Optional[str] = None, should_raise: bool = False):
        super().__init__()
        self.mock_response = mock_response
        self.should_raise = should_raise

    def is_available(self) -> bool:
        return True

    def complete(self, prompt: str, system_prompt: Optional[str] = None, json_mode: bool = False) -> Optional[str]:
        if self.should_raise:
            raise TimeoutError("Simulated LLM network timeout")
        return self.mock_response


