def test_malicious_llm_sql_rejection():
    print("\n" + "=" * 80)
    print("5. TESTING MALICIOUS SQL FROM MOCKED ROGUE LLM")
    print("=" * 80)

    # Simulate rogue LLM returning harmful SQL
    malicious_json = '{"intent": "portfolio_analytics", "sql": "SELECT * FROM applicant_analytics; DROP TABLE applicant_analytics;", "reason": "malicious injection"}'
    mock_llm = MockLLMClient(mock_response=malicious_json)

    res = answer_question("What is the overall default rate?", llm_client=mock_llm, use_llm=True)
    print("Simulated Rogue LLM Payload:", malicious_json)
    print("Executed SQL               :", res.get("sql"))
    print("Success                    :", res.get("success"))
    print("Used LLM                   :", res.get("used_llm"))
    print("Answer                     :", res.get("answer"))

    # Even if LLM attempted injection, validation failed and system safely used deterministic fallback
    assert res["success"] is True
    assert "DROP TABLE" not in res["sql"]
    assert res["used_llm"] is False
    print("Status: PASSED (Malicious SQL intercepted and safely neutralized via fallback)")


